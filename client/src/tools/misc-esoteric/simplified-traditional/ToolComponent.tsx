const T2S: Record<string, string> = {};
for (const [k, v] of Object.entries(S2T)) {
  if (!T2S[v]) T2S[v] = k;
}

function convert(text: string, map: Record<string, string>): string {
  let result = '';
  for (const ch of text) {
    result += map[ch] ?? ch;
  }
  return result;
}

const ToolComponent = (props: ToolProps) => (
  <SimpleTool
    {...props}
    execute={(input: string, mode: string) => {
      if (mode === 'decode') return convert(input, T2S);
      return convert(input, S2T);
    }}
    modeOptions={[
      { value: 'encode', label: '简→繁' },
      { value: 'decode', label: '繁→简' },
    ]}
  />
);

