const EBCDIC_TO_ASCII: Record<number, number> = {};
for (const k of Object.keys(ASCII_TO_EBCDIC)) {
  const ak = parseInt(k, 10);
  EBCDIC_TO_ASCII[ASCII_TO_EBCDIC[ak]] = ak;
}

const ToolComponent = (props: ToolProps) => (
  <SimpleTool
    {...props}
    execute={(input: string, mode: string) => {
      try {
        if (mode === 'encode') {
          const result: string[] = [];
          for (const ch of Array.from(input)) {
            const code = ch.charCodeAt(0);
            const ebcdic = ASCII_TO_EBCDIC[code];
            if (ebcdic === undefined) {
              result.push('3f');
            } else {
              result.push(ebcdic.toString(16).padStart(2, '0'));
            }
          }
          return result.join(' ');
        }
        const clean = input.replace(/[\s-]/g, '');
        const hexArr = clean.match(/.{1,2}/g);
        if (!hexArr) return '错误: 无效的十六进制输入';
        let result = '';
        for (const h of hexArr) {
          const ebcdic = parseInt(h, 16);
          const ascii = EBCDIC_TO_ASCII[ebcdic];
          if (ascii === undefined) {
            result += '?';
          } else {
            result += String.fromCharCode(ascii);
          }
        }
        return result;
      } catch (e) {
        return `错误: ${e instanceof Error ? e.message : '无效输入'}`;
      }
    }}
    modeOptions={[
      { value: 'encode', label: '编码' },
      { value: 'decode', label: '解码' },
    ]}
  />
);

export default ToolComponent;
