const ToolComponent = (props: ToolProps) => (
  <SimpleTool
    {...props}
    execute={(input: string) => {
      const ct = input.trim().split(';')[0].trim().toLowerCase();
      if (!ct) {
        const list = Object.entries(MIME_INFO).map(
          ([mime, info]) => `${mime}\n  名称: ${info.name}\n  说明: ${info.desc}\n  扩展名: ${info.exts.join(', ') || '无'}`,
        );
        return `请输入 Content-Type 或扩展名查询。\n\n支持列表:\n\n${list.join('\n\n')}`;
      }
      const entry = Object.entries(MIME_INFO).find(
        ([mime, info]) =>
          mime === ct || info.exts.includes(ct.startsWith('.') ? ct : `.${ct}`),
      );
      if (!entry) {
        return `Content-Type "${ct}" 不在常见列表中。`;
      }
      const [mime, info] = entry;
      return [
        `MIME 类型: ${mime}`,
        `名称: ${info.name}`,
        `说明: ${info.desc}`,
        `常见扩展名: ${info.exts.join(', ') || '无'}`,
      ].join('\n');
    }}
  />
);

export default ToolComponent;
