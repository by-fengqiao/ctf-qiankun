const SERVICE_INDEX: Record<string, string> = {};
for (const [port, info] of Object.entries(PORTS)) {
  SERVICE_INDEX[info.name.toLowerCase()] = port;
}

const ToolComponent = (props: ToolProps) => (
  <SimpleTool
    {...props}
    execute={(input: string) => {
      const query = input.trim().toLowerCase();
      if (!query) {
        const all = Object.entries(PORTS).map(
          ([p, info]) => `${p}/${info.proto}\t${info.name}\t${info.desc}`,
        );
        return `请输入端口号或服务名称查询。\n\n常用端口列表:\n\n${all.join('\n')}`;
      }
      const byPort = PORTS[query];
      if (byPort) {
        return [
          `端口: ${query}`,
          `服务: ${byPort.name}`,
          `协议: ${byPort.proto}`,
          `说明: ${byPort.desc}`,
        ].join('\n');
      }
      const port = SERVICE_INDEX[query];
      if (port) {
        const info = PORTS[port];
        return [
          `服务: ${query}`,
          `端口: ${port}`,
          `协议: ${info.proto}`,
          `说明: ${info.desc}`,
        ].join('\n');
      }
      const portNum = parseInt(query, 10);
      if (!isNaN(portNum) && portNum >= 0 && portNum <= 65535) {
        const range = portNum <= 1023 ? '知名端口 (0-1023)' : portNum <= 49151 ? '注册端口 (1024-49151)' : '动态端口 (49152-65535)';
        return `端口 ${query} 不在常见列表中。\n\n端口范围: ${range}`;
      }
      throw new Error('未找到匹配的端口或服务');
    }}
  />
);

export default ToolComponent;
